SELECT
    SK_ID_CURR,
    count(*) AS PREV_APPLICATION_COUNT,
    count(*) FILTER (WHERE NAME_CONTRACT_STATUS = 'Approved') AS PREV_APPROVED_COUNT,
    count(*) FILTER (WHERE NAME_CONTRACT_STATUS = 'Refused') AS PREV_REFUSED_COUNT,
    count(*) FILTER (WHERE NAME_CONTRACT_STATUS = 'Canceled') AS PREV_CANCELED_COUNT,
    avg(CAST(NAME_CONTRACT_STATUS = 'Refused' AS DOUBLE)) AS PREV_REFUSED_SHARE,
    count(*) FILTER (WHERE DAYS_DECISION >= -365) AS PREV_APPLICATIONS_LAST_YEAR,
    count(*) FILTER (WHERE NAME_CONTRACT_STATUS = 'Refused' AND DAYS_DECISION >= -365) AS PREV_REFUSED_LAST_YEAR,
    -max(DAYS_DECISION) AS PREV_DAYS_SINCE_LAST_DECISION,
    -max(DAYS_DECISION) FILTER (WHERE NAME_CONTRACT_STATUS = 'Approved') AS PREV_DAYS_SINCE_LAST_APPROVAL,
    -max(DAYS_DECISION) FILTER (WHERE NAME_CONTRACT_STATUS = 'Refused') AS PREV_DAYS_SINCE_LAST_REFUSAL,
    avg(AMT_APPLICATION) AS PREV_MEAN_AMT_APPLICATION,
    avg(AMT_CREDIT) FILTER (WHERE NAME_CONTRACT_STATUS = 'Approved') AS PREV_MEAN_APPROVED_CREDIT,
    max(AMT_CREDIT) FILTER (WHERE NAME_CONTRACT_STATUS = 'Approved') AS PREV_MAX_APPROVED_CREDIT,
    avg(AMT_ANNUITY) FILTER (WHERE NAME_CONTRACT_STATUS = 'Approved') AS PREV_MEAN_APPROVED_ANNUITY,
    avg(AMT_CREDIT / nullif(AMT_APPLICATION, 0)) AS PREV_MEAN_CREDIT_TO_APPLICATION,
    min(AMT_CREDIT / nullif(AMT_APPLICATION, 0)) AS PREV_MIN_CREDIT_TO_APPLICATION,
    avg(RATE_DOWN_PAYMENT) AS PREV_MEAN_DOWN_PAYMENT_RATE,
    avg(CNT_PAYMENT) FILTER (WHERE NAME_CONTRACT_STATUS = 'Approved') AS PREV_MEAN_TERM,
    avg(CNT_PAYMENT * AMT_ANNUITY / nullif(AMT_CREDIT, 0)) FILTER (WHERE NAME_CONTRACT_STATUS = 'Approved') AS PREV_MEAN_PAYBACK_RATIO,
    avg(CAST(NAME_YIELD_GROUP = 'high' AS DOUBLE)) AS PREV_HIGH_YIELD_SHARE,
    avg(CAST(NAME_CONTRACT_TYPE = 'Revolving loans' AS DOUBLE)) AS PREV_REVOLVING_SHARE,
    avg(CAST(NAME_CLIENT_TYPE = 'New' AS DOUBLE)) AS PREV_NEW_CLIENT_SHARE,
    count(*) FILTER (
        WHERE NAME_CONTRACT_STATUS = 'Approved' AND DAYS_FIRST_DUE IS NOT NULL AND DAYS_TERMINATION IS NULL
    ) AS PREV_OPEN_LOAN_COUNT,
    avg(DAYS_LAST_DUE - DAYS_LAST_DUE_1ST_VERSION) AS PREV_MEAN_DAYS_LATE_CLOSE
FROM previous_application_valid
GROUP BY SK_ID_CURR
