WITH monthly AS (
    SELECT
        b.SK_ID_CURR,
        bb.SK_ID_BUREAU,
        bb.MONTHS_BALANCE,
        bb.STATUS,
        CASE
            WHEN bb.STATUS IN ('0', '1', '2', '3', '4', '5') THEN CAST(bb.STATUS AS INTEGER)
            WHEN bb.STATUS = 'C' THEN 0
        END AS bucket
    FROM bureau_balance_valid AS bb
    JOIN bureau_valid AS b ON bb.SK_ID_BUREAU = b.SK_ID_BUREAU
),
with_previous AS (
    SELECT
        *,
        lag(bucket) OVER (PARTITION BY SK_ID_BUREAU ORDER BY MONTHS_BALANCE) AS previous_bucket
    FROM monthly
)
SELECT
    SK_ID_CURR,
    avg(CAST(STATUS = '0' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -6) AS BB_SHARE_0_6M,
    avg(CAST(STATUS = '1' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -6) AS BB_SHARE_1_6M,
    avg(CAST(STATUS = '2' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -6) AS BB_SHARE_2_6M,
    avg(CAST(STATUS = '3' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -6) AS BB_SHARE_3_6M,
    avg(CAST(STATUS = '4' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -6) AS BB_SHARE_4_6M,
    avg(CAST(STATUS = '5' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -6) AS BB_SHARE_5_6M,
    avg(CAST(STATUS = 'C' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -6) AS BB_SHARE_C_6M,
    avg(CAST(STATUS = 'X' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -6) AS BB_SHARE_X_6M,
    avg(CAST(STATUS = '0' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_SHARE_0_12M,
    avg(CAST(STATUS = '1' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_SHARE_1_12M,
    avg(CAST(STATUS = '2' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_SHARE_2_12M,
    avg(CAST(STATUS = '3' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_SHARE_3_12M,
    avg(CAST(STATUS = '4' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_SHARE_4_12M,
    avg(CAST(STATUS = '5' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_SHARE_5_12M,
    avg(CAST(STATUS = 'C' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_SHARE_C_12M,
    avg(CAST(STATUS = 'X' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_SHARE_X_12M,
    avg(CAST(STATUS = '0' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -24) AS BB_SHARE_0_24M,
    avg(CAST(STATUS = '1' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -24) AS BB_SHARE_1_24M,
    avg(CAST(STATUS = '2' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -24) AS BB_SHARE_2_24M,
    avg(CAST(STATUS = '3' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -24) AS BB_SHARE_3_24M,
    avg(CAST(STATUS = '4' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -24) AS BB_SHARE_4_24M,
    avg(CAST(STATUS = '5' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -24) AS BB_SHARE_5_24M,
    avg(CAST(STATUS = 'C' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -24) AS BB_SHARE_C_24M,
    avg(CAST(STATUS = 'X' AS DOUBLE)) FILTER (WHERE MONTHS_BALANCE >= -24) AS BB_SHARE_X_24M,
    count(*) AS BB_MONTH_COUNT,
    max(bucket) AS BB_WORST_BUCKET,
    max(bucket) FILTER (WHERE MONTHS_BALANCE >= -12) AS BB_WORST_BUCKET_12M,
    avg(CAST(bucket > previous_bucket AS DOUBLE)) FILTER (WHERE previous_bucket IS NOT NULL AND bucket IS NOT NULL) AS BB_ROLL_RATE,
    avg(CAST(bucket > previous_bucket AS DOUBLE)) FILTER (WHERE previous_bucket IS NOT NULL AND bucket IS NOT NULL AND MONTHS_BALANCE >= -12) AS BB_ROLL_RATE_12M
FROM with_previous
GROUP BY SK_ID_CURR
