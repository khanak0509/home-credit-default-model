SELECT
    * EXCLUDE (TARGET, CODE_GENDER),
    AMT_CREDIT / nullif(AMT_INCOME_TOTAL, 0) AS CREDIT_TO_INCOME,
    AMT_ANNUITY / nullif(AMT_INCOME_TOTAL, 0) AS ANNUITY_TO_INCOME,
    AMT_ANNUITY / nullif(AMT_CREDIT, 0) AS ANNUITY_TO_CREDIT,
    AMT_CREDIT / nullif(AMT_GOODS_PRICE, 0) AS CREDIT_TO_GOODS,
    AMT_INCOME_TOTAL / nullif(CNT_FAM_MEMBERS, 0) AS INCOME_PER_FAMILY_MEMBER,
    -DAYS_BIRTH / 365.25 AS AGE_YEARS,
    -DAYS_EMPLOYED / 365.25 AS EMPLOYMENT_YEARS,
    DAYS_EMPLOYED / DAYS_BIRTH AS EMPLOYED_TO_AGE,
    -DAYS_ID_PUBLISH / 365.25 AS ID_PUBLISH_YEARS,
    -DAYS_LAST_PHONE_CHANGE / 365.25 AS PHONE_CHANGE_YEARS,
    FLAG_DOCUMENT_2 +
        FLAG_DOCUMENT_3 +
        FLAG_DOCUMENT_4 +
        FLAG_DOCUMENT_5 +
        FLAG_DOCUMENT_6 +
        FLAG_DOCUMENT_7 +
        FLAG_DOCUMENT_8 +
        FLAG_DOCUMENT_9 +
        FLAG_DOCUMENT_10 +
        FLAG_DOCUMENT_11 +
        FLAG_DOCUMENT_12 +
        FLAG_DOCUMENT_13 +
        FLAG_DOCUMENT_14 +
        FLAG_DOCUMENT_15 +
        FLAG_DOCUMENT_16 +
        FLAG_DOCUMENT_17 +
        FLAG_DOCUMENT_18 +
        FLAG_DOCUMENT_19 +
        FLAG_DOCUMENT_20 +
        FLAG_DOCUMENT_21 AS DOCUMENT_COUNT,
    FLAG_MOBIL + FLAG_EMP_PHONE + FLAG_WORK_PHONE + FLAG_CONT_MOBILE + FLAG_PHONE + FLAG_EMAIL AS CONTACT_FLAG_COUNT,
    REG_REGION_NOT_LIVE_REGION + REG_REGION_NOT_WORK_REGION + LIVE_REGION_NOT_WORK_REGION
        + REG_CITY_NOT_LIVE_CITY + REG_CITY_NOT_WORK_CITY + LIVE_CITY_NOT_WORK_CITY AS ADDRESS_MISMATCH_COUNT,
    list_avg(list_filter([EXT_SOURCE_1, EXT_SOURCE_2, EXT_SOURCE_3], lambda x: x IS NOT NULL)) AS EXT_SOURCE_MEAN,
    list_min(list_filter([EXT_SOURCE_1, EXT_SOURCE_2, EXT_SOURCE_3], lambda x: x IS NOT NULL)) AS EXT_SOURCE_MIN,
    list_max(list_filter([EXT_SOURCE_1, EXT_SOURCE_2, EXT_SOURCE_3], lambda x: x IS NOT NULL)) AS EXT_SOURCE_MAX,
    list_aggregate(list_filter([EXT_SOURCE_1, EXT_SOURCE_2, EXT_SOURCE_3], lambda x: x IS NOT NULL), 'stddev_pop') AS EXT_SOURCE_STD,
    EXT_SOURCE_1 * EXT_SOURCE_2 * EXT_SOURCE_3 AS EXT_SOURCE_PRODUCT
FROM application_clean
