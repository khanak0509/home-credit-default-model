WITH monthly AS (
    SELECT
        *,
        AMT_BALANCE / nullif(AMT_CREDIT_LIMIT_ACTUAL, 0) AS utilization,
        AMT_PAYMENT_TOTAL_CURRENT / nullif(AMT_INST_MIN_REGULARITY, 0) AS payment_to_minimum
    FROM credit_card_valid
)
SELECT
    SK_ID_CURR,
    count(DISTINCT SK_ID_PREV) AS CC_CARD_COUNT,
    count(*) AS CC_MONTH_COUNT,
    avg(utilization) AS CC_MEAN_UTILIZATION,
    max(utilization) AS CC_MAX_UTILIZATION,
    avg(utilization) FILTER (WHERE MONTHS_BALANCE >= -3) AS CC_MEAN_UTILIZATION_3M,
    avg(utilization) FILTER (WHERE MONTHS_BALANCE >= -12) AS CC_MEAN_UTILIZATION_12M,
    max(AMT_BALANCE) AS CC_MAX_BALANCE,
    avg(AMT_BALANCE) FILTER (WHERE MONTHS_BALANCE >= -3) AS CC_MEAN_BALANCE_3M,
    max(AMT_CREDIT_LIMIT_ACTUAL) AS CC_MAX_LIMIT,
    avg(AMT_DRAWINGS_ATM_CURRENT) AS CC_MEAN_ATM_DRAWINGS,
    avg(CNT_DRAWINGS_CURRENT) AS CC_MEAN_DRAWING_COUNT,
    avg(payment_to_minimum) AS CC_MEAN_PAYMENT_TO_MINIMUM,
    avg(CAST(AMT_PAYMENT_TOTAL_CURRENT < AMT_INST_MIN_REGULARITY AS DOUBLE))
        FILTER (WHERE AMT_INST_MIN_REGULARITY > 0) AS CC_BELOW_MINIMUM_SHARE,
    max(SK_DPD) AS CC_MAX_DPD,
    max(SK_DPD_DEF) AS CC_MAX_DPD_DEF,
    max(SK_DPD) FILTER (WHERE MONTHS_BALANCE >= -12) AS CC_MAX_DPD_12M,
    avg(CAST(SK_DPD > 0 AS DOUBLE)) AS CC_DPD_MONTH_SHARE,
    -max(MONTHS_BALANCE) AS CC_MONTHS_SINCE_LAST_RECORD
FROM monthly
GROUP BY SK_ID_CURR
