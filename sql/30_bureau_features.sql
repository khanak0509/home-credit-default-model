SELECT
    SK_ID_CURR,
    count(*) AS BUREAU_CREDIT_COUNT,
    count(*) FILTER (WHERE CREDIT_ACTIVE = 'Active') AS BUREAU_ACTIVE_COUNT,
    count(*) FILTER (WHERE CREDIT_ACTIVE = 'Closed') AS BUREAU_CLOSED_COUNT,
    count(*) FILTER (WHERE CREDIT_ACTIVE = 'Bad debt') AS BUREAU_BAD_DEBT_COUNT,
    count(*) FILTER (WHERE CREDIT_ACTIVE = 'Active') / count(*) AS BUREAU_ACTIVE_SHARE,
    sum(AMT_CREDIT_SUM_OVERDUE) AS BUREAU_TOTAL_OVERDUE,
    max(AMT_CREDIT_SUM_OVERDUE) AS BUREAU_MAX_OVERDUE,
    max(AMT_CREDIT_MAX_OVERDUE) AS BUREAU_MAX_EVER_OVERDUE,
    max(CREDIT_DAY_OVERDUE) AS BUREAU_MAX_DAYS_OVERDUE,
    avg(CAST(CREDIT_DAY_OVERDUE > 0 AS DOUBLE)) AS BUREAU_OVERDUE_SHARE,
    sum(AMT_CREDIT_SUM_DEBT) / nullif(sum(AMT_CREDIT_SUM), 0) AS BUREAU_DEBT_TO_CREDIT,
    sum(AMT_CREDIT_SUM_DEBT) FILTER (WHERE CREDIT_ACTIVE = 'Active')
        / nullif(sum(AMT_CREDIT_SUM) FILTER (WHERE CREDIT_ACTIVE = 'Active'), 0) AS BUREAU_ACTIVE_DEBT_TO_CREDIT,
    sum(AMT_CREDIT_SUM) FILTER (WHERE CREDIT_ACTIVE = 'Active') AS BUREAU_ACTIVE_CREDIT_SUM,
    sum(AMT_CREDIT_SUM_DEBT) FILTER (WHERE CREDIT_ACTIVE = 'Active') AS BUREAU_ACTIVE_DEBT_SUM,
    sum(AMT_CREDIT_SUM_LIMIT) FILTER (WHERE CREDIT_ACTIVE = 'Active') AS BUREAU_ACTIVE_LIMIT_SUM,
    count(DISTINCT CREDIT_TYPE) AS BUREAU_CREDIT_TYPE_COUNT,
    -max(DAYS_CREDIT) AS BUREAU_DAYS_SINCE_LAST_CREDIT,
    -min(DAYS_CREDIT) AS BUREAU_DAYS_SINCE_FIRST_CREDIT,
    count(*) FILTER (WHERE DAYS_CREDIT >= -365) AS BUREAU_CREDITS_LAST_YEAR,
    sum(CNT_CREDIT_PROLONG) AS BUREAU_PROLONG_COUNT
FROM bureau_valid
GROUP BY SK_ID_CURR
