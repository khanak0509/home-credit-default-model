CREATE OR REPLACE VIEW installments_valid AS
SELECT *
FROM installments_payments
WHERE DAYS_INSTALMENT <= 0
  AND coalesce(DAYS_ENTRY_PAYMENT, 0) <= 0;

CREATE OR REPLACE VIEW bureau_valid AS
SELECT *
FROM bureau
WHERE DAYS_CREDIT <= 0
  AND coalesce(DAYS_ENDDATE_FACT, 0) <= 0
  AND coalesce(DAYS_CREDIT_UPDATE, 0) <= 0;

CREATE OR REPLACE VIEW bureau_balance_valid AS
SELECT bb.*
FROM bureau_balance AS bb
SEMI JOIN bureau_valid AS b ON bb.SK_ID_BUREAU = b.SK_ID_BUREAU
WHERE bb.MONTHS_BALANCE <= 0;

CREATE OR REPLACE VIEW previous_application_valid AS
SELECT * REPLACE (
    CASE WHEN DAYS_FIRST_DRAWING <= 0 THEN DAYS_FIRST_DRAWING END AS DAYS_FIRST_DRAWING,
    CASE WHEN DAYS_FIRST_DUE <= 0 THEN DAYS_FIRST_DUE END AS DAYS_FIRST_DUE,
    CASE WHEN DAYS_LAST_DUE_1ST_VERSION <= 0 THEN DAYS_LAST_DUE_1ST_VERSION END AS DAYS_LAST_DUE_1ST_VERSION,
    CASE WHEN DAYS_LAST_DUE <= 0 THEN DAYS_LAST_DUE END AS DAYS_LAST_DUE,
    CASE WHEN DAYS_TERMINATION <= 0 THEN DAYS_TERMINATION END AS DAYS_TERMINATION
)
FROM previous_application
WHERE DAYS_DECISION <= 0;

CREATE OR REPLACE VIEW pos_cash_valid AS
SELECT *
FROM pos_cash_balance
WHERE MONTHS_BALANCE <= 0;

CREATE OR REPLACE VIEW credit_card_valid AS
SELECT *
FROM credit_card_balance
WHERE MONTHS_BALANCE <= 0;
